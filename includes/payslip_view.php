<?php
declare(strict_types=1);

function load_payslip(int $id): ?array
{
    return one(
        'SELECT p.*, r.period, r.status AS run_status,
                e.name, e.emp_no, e.designation, e.nic, e.epf_no, e.bank_name, e.bank_account,
                d.name AS department
           FROM payslips p
           JOIN payroll_runs r ON r.id = p.run_id
           JOIN employees e ON e.id = p.employee_id
           LEFT JOIN departments d ON d.id = e.department_id
          WHERE p.id = ?',
        [$id]
    );
}

function render_payslip(array $s): void
{
    $rates = payroll_rates();
    $earnings = [
        ['Basic salary', $s['basic']],
        ['Allowance (EPF-liable)', $s['fixed_allowance']],
        ['Other allowances', $s['other_allowance']],
    ];
    if ((float) $s['ot_pay'] > 0) {
        $earnings[] = ['Overtime (' . (float) $s['ot_hours'] . ' h × ' . $rates['ot_multiplier'] . ')', $s['ot_pay']];
    }
    if ((float) $s['nopay_deduction'] > 0) {
        $earnings[] = ['No-pay leave (' . (float) $s['nopay_days'] . ' days)', -$s['nopay_deduction']];
    }
    $deductions = [
        ['EPF – employee ' . ($rates['epf_employee'] * 100) . '%', $s['epf_employee']],
        ['APIT (income tax)', $s['apit']],
    ];
    if ((float) $s['other_deductions'] > 0) {
        $deductions[] = ['Other deductions', $s['other_deductions']];
    }
    $totalDeductions = (float) $s['epf_employee'] + (float) $s['apit'] + (float) $s['other_deductions'];
    ?>
    <div class="card-app payslip">
        <div class="payslip-head">
            <div>
                <div class="text-body-secondary small text-uppercase fw-semibold">Payslip</div>
                <h2><?= e(period_label($s['period'])) ?></h2>
                <?php if ($s['run_status'] === 'draft'): ?><span class="badge badge-soft badge-warning mt-1">Draft – not final</span><?php endif; ?>
            </div>
            <div class="text-end">
                <div class="fw-bold"><?= e(config('company')) ?></div>
                <div class="small text-body-secondary">Generated by <?= e(config('app_name')) ?></div>
            </div>
        </div>

        <div class="payslip-meta">
            <div><span>Employee</span><strong><?= e($s['name']) ?></strong></div>
            <div><span>Employee no</span><strong><?= e($s['emp_no']) ?></strong></div>
            <div><span>Designation</span><strong><?= e($s['designation'] ?: '—') ?></strong></div>
            <div><span>Department</span><strong><?= e($s['department'] ?: '—') ?></strong></div>
            <div><span>NIC</span><strong><?= e($s['nic'] ?: '—') ?></strong></div>
            <div><span>EPF no</span><strong><?= e($s['epf_no'] ?: '—') ?></strong></div>
            <div><span>Bank</span><strong><?= e(trim(($s['bank_name'] ?? '') . ' ' . ($s['bank_account'] ?? '')) ?: '—') ?></strong></div>
        </div>

        <div class="payslip-cols">
            <table class="payslip-table">
                <tr><th>Earnings</th><th class="num">Rs.</th></tr>
                <?php foreach ($earnings as [$label, $amount]): ?>
                    <tr><td><?= e($label) ?></td><td class="num"><?= money($amount, false) ?></td></tr>
                <?php endforeach; ?>
                <tr class="total"><td>Gross pay</td><td class="num"><?= money($s['gross_pay'], false) ?></td></tr>
            </table>
            <table class="payslip-table">
                <tr><th>Deductions</th><th class="num">Rs.</th></tr>
                <?php foreach ($deductions as [$label, $amount]): ?>
                    <tr><td><?= e($label) ?></td><td class="num"><?= money($amount, false) ?></td></tr>
                <?php endforeach; ?>
                <tr class="total"><td>Total deductions</td><td class="num"><?= money($totalDeductions, false) ?></td></tr>
            </table>
        </div>

        <div class="net-pay">
            <span class="fw-semibold">Net pay</span>
            <strong><?= money($s['net_pay']) ?></strong>
        </div>

        <div class="employer-box">
            Paid by the employer on top of your salary:
            EPF <?= $rates['epf_employer'] * 100 ?>% <strong><?= money($s['epf_employer']) ?></strong> ·
            ETF <?= $rates['etf_employer'] * 100 ?>% <strong><?= money($s['etf_employer']) ?></strong>.
            Total EPF credited to your account this month: <strong><?= money((float) $s['epf_employee'] + (float) $s['epf_employer']) ?></strong>
            (on earnings of <?= money($s['epf_base']) ?>).
        </div>
    </div>
    <?php
}
